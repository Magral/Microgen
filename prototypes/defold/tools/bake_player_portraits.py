"""Add organ-free Godot portraits for the six runtime morphology families."""
import argparse
from pathlib import Path

from bake_art import MAIN, actor

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    names = [f"body_{index}" for index in range(6)]
    sizes = [actor(args.source, name) for name in names]
    data = ["-- Generated by tools/bake_player_portraits.py.", "return {"]
    data.extend(f"    {{{width}, {height}}}," for width, height in sizes)
    (MAIN / "body_art.lua").write_text("\n".join(data + ["}", ""]))
    atlas = MAIN / "cells.atlas"
    content = [line for line in atlas.read_text().splitlines() if "/main/art/body_" not in line]
    atlas.write_text("\n".join([f'images {{ image: "/main/art/{name}.png" }}' for name in names] + content + [""]))
