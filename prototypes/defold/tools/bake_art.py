"""Pack real Godot captures for the Defold visual benchmark."""
import argparse
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

MAIN = Path(__file__).resolve().parents[1] / "main"
ART = MAIN / "art"
WIDTH = 2460
HEIGHT = 1080


def save(image, name):
    image.save(ART / f"{name}.png", optimize=True)


def atlas(name, assets, inner_padding=2):
    (MAIN / f"{name}.atlas").write_text(
        "".join(f'images {{ image: "/main/art/{asset}.png" }}\n' for asset in assets)
        + f"margin: 2\nextrude_borders: 2\ninner_padding: {inner_padding}\n"
    )


def actor(source, name):
    rgba = np.array(Image.open(source / f"{name}.png").convert("RGBA"))
    alpha = rgba[..., 3:]
    # Godot captures blended content over transparent black. Defold needs
    # straight-alpha textures before making its atlas.
    rgb = np.zeros_like(rgba[..., :3], dtype=np.float32)
    np.divide(rgba[..., :3].astype(np.float32) * 255, alpha, out=rgb, where=alpha > 0)
    rgba[...,:3] = np.clip(rgb, 0, 255).astype(np.uint8)
    image = Image.fromarray(rgba)
    bbox = image.getchannel("A").getbbox()
    if bbox is None or image.width != image.height:
        raise ValueError(f"Invalid Godot portrait {name}")
    x, y = image.width//2, image.height//2
    rx = max(x-bbox[0],bbox[2]-x)+2
    ry = max(y-bbox[1],bbox[3]-y)+2
    if rx > x or ry > y:
        raise ValueError(f"Godot portrait cut by the viewport: {name}")
    image = image.crop((x-rx,y-ry,x+rx,y+ry))
    save(image,name)
    return image.size


def field(name, lobes):
    size = 384
    a = np.linspace(-1, 1, size, dtype=np.float32)
    x, y = np.meshgrid(a, a)
    r, angle = np.hypot(x,y), np.arctan2(y,x)
    contour = .83 + .052*np.cos(lobes*angle) + .022*np.sin(angle*9+.9)
    distance = r-contour
    if name == "field":
        drift = .54 + .22*np.sin(13*x+np.sin(19*y)) + .12*np.cos(18*y-9*x)
        pool = np.clip(-distance/.45,0,1)*drift*.16
        breaks = np.clip(.55+.38*np.cos(5*angle)+.25*np.sin(13*angle),0,1)
        alpha = pool + np.exp(-(distance/.024)**2)*breaks*.38
    else:
        phase = .7 if name == "shield" else -1.0
        breaks = np.clip(.57+.55*np.cos(2*angle-phase),0,1)
        alpha = (np.exp(-(distance/.024)**2)*.66 + np.exp(-(distance/.065)**2)*.20)*breaks
    rgba = np.zeros((size,size,4), dtype=np.uint8)
    rgba[:,:,:3] = (200,232,214)
    rgba[:,:,3] = np.uint8(np.clip(alpha,0,1)*255)
    save(Image.fromarray(rgba),name)


def main():
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument("captures",type=Path)
    source = args.parse_args().captures
    background = Image.open(source / "terrain.png").convert("RGB")
    if background.size != (WIDTH,HEIGHT):
        raise ValueError(f"Unexpected reference resolution {background.size}")
    save(background, "terrain")
    atlas("world", ["terrain"], inner_padding=0)
    names = sorted(file.stem for file in source.glob("actor_*.png"))+["player"]
    if len(names) != 20:
        raise ValueError("The fixed arena needs 19 enemies and one player.")
    dims = {name:actor(source,name) for name in names}
    (MAIN / "arena_art.lua").write_text(
        "-- Generated by tools/bake_art.py.\nreturn {\n"
        + "".join(f"    {name} = {{{w}, {h}}},\n" for name,(w,h) in dims.items()) + "}\n"
    )
    field("field",5)
    field("shield",3)
    field("surge",7)
    speck = Image.new("RGBA",(64,64))
    draw = ImageDraw.Draw(speck)
    draw.ellipse((7,9,58,55),fill=(68,185,168,57))
    draw.polygon([(29,13),(50,26),(43,44),(25,51),(14,34)],fill=(98,211,186,192))
    draw.polygon([(29,17),(44,27),(37,33),(25,32)],fill=(220,252,214,221))
    save(speck,"speck")
    atlas("cells",names+["field","shield","surge","speck"])


if __name__ == "__main__":
    main()
